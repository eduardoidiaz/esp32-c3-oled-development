// Your verified coordinate-centered wrapper function
void draw_pixel(int x, int y, bool color) {
    if (x < 0 || x >= SCREEN_WIDTH || y < 0 || y >= SCREEN_HEIGHT) return;
    
    // Shift X right by your verified 20-pixel offset marker
    int real_x = x + 20; 
    
    int index = real_x + (y / 8) * 128;
    if (color) {
        frame_canvas[index] |= (1 << (y % 8));   
    } else {
        frame_canvas[index] &= ~(1 << (y % 8));  
    }
}

// 🎯 FIXED TEXT RENDER ENGINE
// Loops through character bitmaps and prints them correctly left-to-right
void draw_string(int x, int y, const char *str) {
    while (*str) {
        char c = *str;
        // Only render standard printable characters within our font array bounds
        if (c >= 32 && c <= 122) {
            int font_index = c - 32;
            for (int row = 0; row < 8; row++) {
                uint8_t byte = font8x8_basic[font_index][row];
                for (int col = 0; col < 8; col++) {
                    // 🛠️ REVERSE THE BIT SAMPLING: Read from bit 7 down to bit 0
                    // This un-flips individual characters horizontally
                    if (byte & (1 << (7 - col))) {
                        draw_pixel(x + col, y + row, true);
                    }
                }
            }
        }
        x += 8; // Move text cursor 8 pixels right for the next character
        str++;
    }
}


void app_main(void)
{
    // 1. Initialize I2C Master Bus
    i2c_master_bus_config_t bus_config = {
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .i2c_port = I2C_NUM_0,
        .scl_io_num = 6,
        .sda_io_num = 5,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t bus_handle;
    i2c_new_master_bus(&bus_config, &bus_handle);

    // 2. Add Raw Device Channel
    i2c_device_config_t dev_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = 0x3C,
        .scl_speed_hz = 400000,
    };
    i2c_master_dev_handle_t global_i2c_dev_handle;
    i2c_master_bus_add_device(bus_handle, &dev_config, &global_i2c_dev_handle);

    // 3. Configure Display Communication Interface
    esp_lcd_panel_io_i2c_config_t io_config = {
        .dev_addr = 0x3C,                 
        .scl_speed_hz = 400000,           
        .control_phase_bytes = 1,
        .dc_bit_offset = 6,
        .lcd_cmd_bits = 8,
        .lcd_param_bits = 8,
    };
    esp_lcd_panel_io_handle_t io_handle = NULL;
    esp_lcd_new_panel_io_i2c(bus_handle, &io_config, &io_handle);

    // 4. Initialize SSD1306 Panel Driver Core (128x64 footprint layout constraints)
    esp_lcd_panel_ssd1306_config_t ssd1306_vendor_cfg = { .height = 64 };
    esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = -1,             
        .bits_per_pixel = 1,              
        .vendor_config = &ssd1306_vendor_cfg, 
    };
    esp_lcd_panel_handle_t panel_handle = NULL;
    esp_lcd_new_panel_ssd1306(io_handle, &panel_config, &panel_handle);
    
    esp_lcd_panel_reset(panel_handle);
    esp_lcd_panel_init(panel_handle);
    esp_lcd_panel_set_gap(panel_handle, 0, 0); 

    // 🛠️ AXIS FIX: Keeps text un-mirrored and left-to-right!
    // esp_lcd_panel_mirror(panel_handle, true, false);
    esp_lcd_panel_disp_on_off(panel_handle, true);

    // 5. Setup Onboard LED (GPIO 8)
    gpio_reset_pin(LED_PIN_B);
    gpio_set_direction(LED_PIN_B, GPIO_MODE_OUTPUT);
    int led_state = 0;

    int counter = 0;
    char counter_string[32];

    // 🧼 STARTUP BLANK SWEEP: Wipe the entire 128x64 internal memory via esp_lcd
    memset(frame_canvas, 0x00, sizeof(frame_canvas));
    esp_lcd_panel_draw_bitmap(panel_handle, 0, 0, 127, 63, frame_canvas);
    vTaskDelay(pdMS_TO_TICKS(100)); // Let the hardware settle

    while (1) {
        gpio_set_level(LED_PIN_B, led_state);
        led_state = !led_state;

        // 🎨 Clear display buffer array space to pure black
        memset(frame_canvas, 0x00, sizeof(frame_canvas));

        // 🎨 DRAW REAL TEXT STRINGS ON THE CANVAS BUFFER
        draw_string(8, 0,  "ESP32-C3");
        draw_string(6, 8, "WARNINGS");
        draw_string(6, 16, "CLEARED!");

        // 🎨 DRAW A LIVE REAL-TIME INCREMENTING COUNTER ROW
        snprintf(counter_string, sizeof(counter_string), "Count: %d", counter++);
        draw_string(4, 24, counter_string);

        // 🚀 FLUSH CANVAS TO PHYSICAL GLASS: Draws everything instantly and keeps hidden rows dark
        esp_lcd_panel_draw_bitmap(panel_handle, 0, 0, 127, 63, frame_canvas);

        vTaskDelay(pdMS_TO_TICKS(1000)); // Delay 1 second per loop iteration
    }
}

